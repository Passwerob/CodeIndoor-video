#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
Generate a high-quality laptop 3D model with the DeepSeek API
"""

import sys
import io
import json
from pathlib import Path
from openai import OpenAI

sys.path.insert(0, str(Path(__file__).parent / "adsl-core"))
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

print("=" * 80)
print(" " * 20 + "🤖 DeepSeek AI Laptop Generation")
print("=" * 80)
print()

# Read the API key
key_file = Path(__file__).parent / "adsl-agents/configs/keys/deepseek_key.txt"
api_key = __import__("os").environ.get("DEEPSEEK_API_KEY", "").strip()
if not api_key:
    api_key = key_file.read_text().strip()  # legacy key file

client = OpenAI(
    api_key=api_key,
    base_url="https://api.deepseek.com/v1"
)

# Ask DeepSeek to generate a design
print("🎨 Requesting a laptop design from DeepSeek...")
print("-" * 80)

prompt = """你是一个专业的 3D 建模专家。请使用 aDSL（一个 Python 3D 建模 DSL）设计一个现代游戏笔记本电脑。

aDSL 语法：
- Asset(label="名称") 创建容器
- asset.attach_part("部件名", 图元) 添加部件
- 图元类型：
  * Cube(scale=(x,y,z), center=(x,y,z), color=(r,g,b))
  * Cylinder(radius=r, height=h, center=(x,y,z), color=(r,g,b))
  * Sphere(radius=r, center=(x,y,z), color=(r,g,b))

**重要的坐标系统：**
- Y 轴向上（垂直）
- 底座在 Y=0 附近
- 屏幕应该在 Y 轴正方向立起来
- 屏幕在底座的后方（Z 轴负方向）

要求：
1. 创建一个打开状态的笔记本电脑
2. 底座（键盘部分）应该是扁平的，放在 Y=0 附近
3. 屏幕应该垂直立起，在 Y 轴正向（向上），Z 轴负向（后方）
4. 包含 RGB 机械键盘（至少 50 个按键，彩虹色）
5. 触控板、电源按钮、散热口、扬声器
6. 颜色要协调，键盘要有彩虹渐变效果
7. 整体尺寸合理（底座宽度约 3-4 单位）

直接输出 Python 代码，从 import 开始，不要任何解释文字。"""

response = client.chat.completions.create(
    model="deepseek-chat",
    messages=[{"role": "user", "content": prompt}],
    temperature=0.7,
    max_tokens=3000
)

code = response.choices[0].message.content.strip()

# Extract the code block
if "```python" in code:
    code = code.split("```python")[1].split("```")[0].strip()
elif "```" in code:
    code = code.split("```")[1].split("```")[0].strip()

print()
print("✅ Code generated by DeepSeek:")
print("-" * 80)
print(code[:500] + "..." if len(code) > 500 else code)
print("-" * 80)
print()

# Save the generated code
output_dir = Path(__file__).parent / "outputs/deepseek_laptop_v2"
output_dir.mkdir(parents=True, exist_ok=True)

code_file = output_dir / "generated_code.py"
code_file.write_text(code, encoding='utf-8')
print(f"💾 Generated code saved: {code_file}")
print()

print("🔧 Running the DeepSeek-generated code...")
print("-" * 80)

# Run the code
exec_globals = {}
try:
    exec(code, exec_globals)

    # Find the generated laptop object
    laptop = None
    for name, obj in exec_globals.items():
        if hasattr(obj, 'label') and hasattr(obj, '_children'):
            laptop = obj
            break

    if laptop is None:
        print("❌ Generated laptop object not found")
        sys.exit(1)

    print()
    print("✅ Code ran successfully!")
    print(f"   Model label: {laptop.label}")
    print(f"   Total parts: {len(laptop._children)}")
    print()

    # Serialize
    from core.serialize import asset_to_dict
    import numpy as np

    def numpy_to_python(obj):
        if isinstance(obj, np.ndarray):
            return obj.tolist()
        elif isinstance(obj, (np.integer, np.floating)):
            return obj.item()
        return obj

    laptop_dict = asset_to_dict(laptop)
    laptop_json = json.loads(json.dumps(laptop_dict, default=numpy_to_python))

    # Save JSON
    json_file = output_dir / "laptop.json"
    with open(json_file, 'w', encoding='utf-8') as f:
        json.dump(laptop_json, f, indent=2, ensure_ascii=False)

    size_kb = json_file.stat().st_size / 1024
    print(f"💾 Model saved: {json_file}")
    print(f"   Size: {size_kb:.1f} KB")
    print()

except Exception as e:
    print(f"❌ Execution error: {e}")
    print()
    print("Trying to fix the code...")
    # Automatic repair logic can be added here
    import traceback
    traceback.print_exc()
    sys.exit(1)

# Generate the Blender import script
blender_script = '''import bpy
import json
from pathlib import Path
import math

# Clear the scene
bpy.ops.object.select_all(action='SELECT')
bpy.ops.object.delete()

# Load JSON
json_path = Path(__file__).parent / "laptop.json"
with open(json_path, 'r', encoding='utf-8') as f:
    data = json.load(f)

print("=" * 80)
print("🤖 Importing DeepSeek AI Generated Laptop V2")
print("=" * 80)

def create_material(name, color, is_emissive=False):
    """Create a material"""
    mat = bpy.data.materials.new(name=name)
    mat.use_nodes = True
    nodes = mat.node_tree.nodes
    nodes.clear()

    output = nodes.new('ShaderNodeOutputMaterial')
    bsdf = nodes.new('ShaderNodeBsdfPrincipled')

    bsdf.inputs['Base Color'].default_value = (*color, 1.0)
    bsdf.inputs['Roughness'].default_value = 0.3
    bsdf.inputs['Metallic'].default_value = 0.4

    if is_emissive:
        bsdf.inputs[26].default_value = (*color, 1.0)  # Emission Color
        bsdf.inputs[27].default_value = 3.0  # Emission Strength (brighter)

    mat.node_tree.links.new(bsdf.outputs[0], output.inputs[0])
    return mat

def create_cube(scale, center, color, name, is_emissive=False):
    bpy.ops.mesh.primitive_cube_add(size=1, location=center)
    obj = bpy.context.active_object
    obj.name = name
    obj.scale = scale
    mat = create_material(f"Mat_{name}", color, is_emissive)
    obj.data.materials.append(mat)
    return obj

def create_cylinder(radius, height, center, color, name, is_emissive=False):
    bpy.ops.mesh.primitive_cylinder_add(radius=radius, depth=height, location=center)
    obj = bpy.context.active_object
    obj.name = name
    mat = create_material(f"Mat_{name}", color, is_emissive)
    obj.data.materials.append(mat)
    return obj

def create_sphere(radius, center, color, name, is_emissive=False):
    bpy.ops.mesh.primitive_uv_sphere_add(radius=radius, location=center)
    obj = bpy.context.active_object
    obj.name = name
    mat = create_material(f"Mat_{name}", color, is_emissive)
    obj.data.materials.append(mat)
    return obj

# Create all parts
objects_created = 0
for part_name, part_data in data.get('children', {}).items():
    primitives = part_data.get('primitives', [])

    for prim in primitives:
        prim_type = prim['type']
        params = prim['params']
        color = prim.get('color', [0.8, 0.8, 0.8])

        is_key = part_name.startswith('key_')

        try:
            if prim_type == 'cube':
                scale = params.get('scale', [1, 1, 1])
                center = params.get('center', [0, 0, 0])
                create_cube(scale, center, color, part_name, is_key)
                objects_created += 1

            elif prim_type == 'cylinder':
                radius = params.get('radius', 1.0)
                height = params.get('height', 2.0)
                center = params.get('center', [0, 0, 0])
                create_cylinder(radius, height, center, color, part_name, is_key)
                objects_created += 1

            elif prim_type == 'sphere':
                radius = params.get('radius', 1.0)
                center = params.get('center', [0, 0, 0])
                create_sphere(radius, center, color, part_name, is_key)
                objects_created += 1
        except Exception as e:
            print(f"Error creating {part_name}: {e}")

print(f"✅ Created {objects_created} objects")

# Set up the camera (side angle, so both the screen and keyboard are visible)
bpy.ops.object.camera_add(location=(6, -5, 3))
camera = bpy.context.active_object
camera.rotation_euler = (math.radians(70), 0, math.radians(50))
bpy.context.scene.camera = camera

# Main light
bpy.ops.object.light_add(type='SUN', location=(4, -4, 6))
sun = bpy.context.active_object
sun.data.energy = 2.5

# Fill light
bpy.ops.object.light_add(type='AREA', location=(-2, -3, 3))
area = bpy.context.active_object
area.data.energy = 300
area.rotation_euler = (math.radians(60), 0, math.radians(-30))

# Set the shading mode to Material Preview
for area in bpy.context.screen.areas:
    if area.type == 'VIEW_3D':
        for space in area.spaces:
            if space.type == 'VIEW_3D':
                space.shading.type = 'MATERIAL'

print("=" * 80)
print("✅ DeepSeek AI Laptop V2 imported successfully!")
print(f"   Total objects: {objects_created}")
print("=" * 80)
print()
print("💡 Press 0 for camera view, Z to change shading")
print("   Try 'Rendered' mode to see RGB keyboard glow!")
'''

script_file = output_dir / "blender_import.py"
script_file.write_text(blender_script, encoding='utf-8')

print(f"🎬 Blender script: {script_file}")
print()

# Generate README
readme = f"""# DeepSeek AI Generated Laptop V2

## 🤖 AI Generation Info

- **Model**: DeepSeek Chat
- **Generated at**: {Path(__file__).stat().st_mtime}
- **Parts**: {len(laptop._children)}

## 📂 Files

- `laptop.json` - 3D model data
- `generated_code.py` - Raw code generated by DeepSeek
- `blender_import.py` - Blender import script

## 🚀 Viewing in Blender

```bash
blender --python blender_import.py
```

Or:
1. Open Blender
2. Scripting → Open → blender_import.py
3. Run the script (Alt+P)

## 🎨 Features

- ✅ Modern gaming laptop design
- ✅ RGB mechanical keyboard (rainbow gradient)
- ✅ Screen stands upright
- ✅ Complete details (touchpad, power, cooling, speakers)
- ✅ 100% AI-generated
"""

readme_file = output_dir / "README.md"
readme_file.write_text(readme, encoding='utf-8')

print("=" * 80)
print("🎉 DeepSeek V2 laptop generation complete!")
print("=" * 80)
print()
print(f"📂 Output directory: {output_dir.absolute()}")
print()
print("🎬 You can now view it in Blender:")
print(f'   blender --python "{output_dir.absolute()}/blender_import.py"')
print()
